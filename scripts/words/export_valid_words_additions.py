"""Generate an insert-only SQL file for `valid_words` rows that the committed
`data/words/seed/valid_words.sql` does not have yet.

Plan 012 U1 fixed a bug in `inflection.py` that wrongly dropped real headwords (e.g.
KOYUN, BOYUN) from `data/words/valid-*.txt`. Regenerating `valid_words.sql` in place would
ask the owner to re-apply ~28k rows against the remote database to add a few hundred new
ones (Invariant 4: agents never write to the remote database; the owner applies seed SQL
by hand). Instead this script writes only the new rows, as `INSERT OR IGNORE`, so the
owner can review and apply a small, readable diff. `valid_words.sql` itself stays
untouched until a future regeneration folds these rows in.

Deterministic: same inputs (the committed `valid_words.sql` and the current
`data/words/valid-{4,5,6}.txt`) always produce the same output. Run directly to (re)write
the file:

    python3 scripts/words/export_valid_words_additions.py
"""

import argparse
import os
import re

from export_seed_sql import (
    VALID_LENGTHS,
    VALID_WORDS_SQL_PATH,
    chunk_valid_words_statements,
    load_valid_words,
    render_seed_content,
)

SCRIPT_DIR = os.path.dirname(os.path.abspath(__file__))
REPO_ROOT = os.path.dirname(os.path.dirname(SCRIPT_DIR))
SEED_DIR = os.path.join(REPO_ROOT, "data", "words", "seed")
ADDITIONS_SQL_PATH = os.path.join(SEED_DIR, "valid_words_012_additions.sql")

# Matches a single `('WORD', LENGTH, ...)` row tuple inside the committed INSERT
# statements; only the word and length are needed to know what is already seeded.
ROW_PATTERN = re.compile(r"\('([^']+)',\s*(\d+),")


def read_committed_words(path: str) -> set:
    """(word, length) pairs already present in a committed valid_words-style seed file."""
    with open(path, encoding="utf-8") as handle:
        content = handle.read()
    return {(word, int(length)) for word, length in ROW_PATTERN.findall(content)}


def compute_additions(baseline_path: str = VALID_WORDS_SQL_PATH, lengths=VALID_LENGTHS) -> list:
    """Rows present in the current `valid-{length}.txt` files but not in `baseline_path`,
    sorted for a deterministic, reviewable diff."""
    committed = read_committed_words(baseline_path)
    current_rows = []
    for length in lengths:
        current_rows.extend(load_valid_words(length))
    return sorted(row for row in current_rows if row not in committed)


def render_additions_sql(baseline_path: str = VALID_WORDS_SQL_PATH, lengths=VALID_LENGTHS) -> str:
    rows = compute_additions(baseline_path, lengths)
    header = (
        "-- Generated by scripts/words/export_valid_words_additions.py. Do not hand-edit;\n"
        "-- regenerate instead. New valid_words rows from Plan 012 U1's inflection-heuristic\n"
        "-- fix (real headwords like KOYUN/BOYUN that were wrongly dropped as inflected\n"
        "-- forms), not yet folded into data/words/seed/valid_words.sql. Same columns and\n"
        "-- source/license convention as valid_words.sql. Safe to re-run: INSERT OR IGNORE."
    )
    return render_seed_content(header, chunk_valid_words_statements(rows))


def parse_args(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    return parser.parse_args(argv)


def main() -> None:
    parse_args()
    os.makedirs(SEED_DIR, exist_ok=True)
    with open(ADDITIONS_SQL_PATH, "w", encoding="utf-8") as handle:
        handle.write(render_additions_sql())
    print(f"wrote {ADDITIONS_SQL_PATH}")


if __name__ == "__main__":
    main()
