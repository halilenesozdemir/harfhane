-- TDK kelimelerini günlük oyun programına ekle (2026-04-01'den itibaren)
-- 4 harfli kelimeler
INSERT OR IGNORE INTO daily_words (word_id, date, length)
SELECT
  w.id,
  date('2026-04-01', '+' || (row_number() OVER (ORDER BY w.id) - 1) || ' days'),
  4
FROM words w
WHERE w.length = 4 AND w.is_active = 1;

-- 5 harfli TDK kelimeleri (Risale kelimeleri hariç — word_list_words'de nurdle slug'ında olanlar)
INSERT OR IGNORE INTO daily_words (word_id, date, length)
SELECT
  w.id,
  date('2026-04-01', '+' || (row_number() OVER (ORDER BY w.id) - 1) || ' days'),
  5
FROM words w
WHERE w.length = 5 AND w.is_active = 1
  AND w.id NOT IN (
    SELECT wlw.word_id FROM word_list_words wlw
    JOIN word_lists wl ON wl.id = wlw.list_id
    WHERE wl.slug = 'nurdle'
  );

